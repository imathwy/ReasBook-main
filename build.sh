#!/usr/bin/env bash

# Build the main Lean project.
#
# BUILD_DOCS:
#   unset -> automatically enabled when doc-gen4 is registered
#   1     -> build docs
#   0     -> skip docs
#
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

log() {
  echo "[build.sh] $(date -u +'%Y-%m-%dT%H:%M:%SZ') $*"
}

prepare_lake_for_toolchain() {
  local project_dir="$1"

  [ -f "$project_dir/lean-toolchain" ] || return 0

  local lake_dir="$project_dir/.lake"
  local stamp="$lake_dir/.reasbook-toolchain"
  local expected
  local actual=""

  expected="$(tr -d '\r\n' < "$project_dir/lean-toolchain")"

  # CI may deliberately provide a branch-specific symlinked .lake.
  # Leave externally managed caches alone.
  if [ -L "$lake_dir" ]; then
    log "using externally managed cache: $lake_dir"
    return 0
  fi

  if [ -f "$stamp" ]; then
    actual="$(tr -d '\r\n' < "$stamp")"
  fi

  if [ -d "$lake_dir" ]; then
    if [ -z "$actual" ]; then
      log "existing unstamped cache found; clearing once: $lake_dir"
      rm -rf "$lake_dir"
    elif [ "$actual" != "$expected" ]; then
      log "Lean toolchain changed:"
      log "  old: $actual"
      log "  new: $expected"
      log "clearing incompatible cache: $lake_dir"
      rm -rf "$lake_dir"
    fi
  fi

  mkdir -p "$lake_dir"
  printf '%s\n' "$expected" > "$stamp"
}

# Protect local builds from native artifacts generated by another Lean version.
prepare_lake_for_toolchain "$ROOT_DIR/ReasBook"

# Detect documentation support automatically unless explicitly overridden.
if [ -z "${BUILD_DOCS+x}" ]; then
  if grep -Eq \
    '^[[:space:]]*require[[:space:]].*doc-gen4' \
    "$ROOT_DIR/ReasBook/lakefile.lean"
  then
    BUILD_DOCS=1
  else
    BUILD_DOCS=0
  fi
fi

log "phase: cache get"
"$ROOT_DIR/scripts/build_reasbook_cache.sh"

# Build Lean first.
#
# There is no reason to spend tens of minutes generating documentation
# before discovering that the actual project does not compile.
log "phase: core build"
"$ROOT_DIR/scripts/build_reasbook_core.sh"

if [ "$BUILD_DOCS" = "1" ]; then
  log "phase: shared docs"
  "$ROOT_DIR/scripts/build_reasbook_shared_docs.sh"

  log "phase: project docs"
  "$ROOT_DIR/scripts/build_reasbook_project_docs.sh"
else
  log "docs disabled or unavailable; skipping"
fi

log "build complete"