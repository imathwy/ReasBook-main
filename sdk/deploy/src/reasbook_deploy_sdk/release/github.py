"""GitHub Release storage and Pages workflow publication adapter."""

from __future__ import annotations

from dataclasses import dataclass
import hashlib
import json
import math
from pathlib import Path
import re
import time
from typing import Any

from reasbook_sdk_common import Command, CommandExecutionError, CommandRunner

from ..errors import DeployExecutionError
from .models import GitHubPublishProfile
from .results import BundleInfo


def _sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        while chunk := handle.read(1024 * 1024):
            digest.update(chunk)
    return digest.hexdigest()


@dataclass(frozen=True)
class GitHubPublication:
    release_id: str
    repository: str
    tag: str
    workflow: str
    status: str
    run_id: int | None = None

    def __post_init__(self) -> None:
        if self.status not in {"planned", "dispatched", "published"}:
            raise DeployExecutionError(
                f"invalid GitHub publication status: {self.status}"
            )

    def public_dict(self) -> dict[str, Any]:
        return {
            "release_id": self.release_id,
            "repository": self.repository,
            "tag": self.tag,
            "workflow": self.workflow,
            "status": self.status,
            "run_id": self.run_id,
        }

    @classmethod
    def from_dict(cls, value: dict[str, Any]) -> "GitHubPublication":
        try:
            return cls(
                release_id=str(value["release_id"]),
                repository=str(value["repository"]),
                tag=str(value["tag"]),
                workflow=str(value["workflow"]),
                status=str(value["status"]),
                run_id=int(value["run_id"]) if value.get("run_id") else None,
            )
        except (KeyError, TypeError, ValueError) as exc:
            raise DeployExecutionError(
                f"invalid GitHub publication record: {exc}"
            ) from exc


class GitHubReleasePublisher:
    """Upload a verified bundle, then dispatch a publish-only Pages workflow."""

    def __init__(
        self,
        profile: GitHubPublishProfile,
        *,
        runner: CommandRunner | None = None,
    ) -> None:
        self.profile = profile
        self.runner = runner or CommandRunner()

    def publish(
        self,
        bundle: BundleInfo,
        *,
        wait: bool = False,
        wait_timeout_seconds: float = 1800.0,
        dry_run: bool = False,
    ) -> GitHubPublication:
        if not math.isfinite(wait_timeout_seconds) or wait_timeout_seconds <= 0:
            raise DeployExecutionError("wait timeout must be positive")
        assets = tuple(
            Path(value).expanduser().resolve()
            for value in (bundle.bundle, bundle.manifest, bundle.checksums)
        )
        for asset in assets:
            if not asset.is_file() or asset.is_symlink():
                raise DeployExecutionError(f"release asset does not exist: {asset}")
        self._validate_assets(bundle, assets)
        tag = (
            f"{self.profile.release_tag_prefix}-"
            f"{bundle.release_id.removeprefix('site-')}"
        )
        if dry_run:
            return GitHubPublication(
                bundle.release_id,
                self.profile.repository,
                tag,
                self.profile.workflow,
                "planned",
            )

        exists = self._run(
            "release",
            "view",
            tag,
            "--repo",
            self.profile.repository,
            "--json",
            "isDraft,targetCommitish,assets",
            check=False,
        )
        if exists.returncode != 0:
            trusted_sha = self._trusted_target()
            self._run(
                "release",
                "create",
                tag,
                "--repo",
                self.profile.repository,
                "--target",
                trusted_sha,
                "--draft",
                "--title",
                f"ReasBook static site {bundle.release_id}",
                "--notes",
                "Immutable static-site bundle generated by reasbook-deploy.",
            )
            self._run(
                "release",
                "upload",
                tag,
                *(str(asset) for asset in assets),
                "--repo",
                self.profile.repository,
            )
        else:
            tag_target = self._tag_target(tag)
            missing = self._validate_existing_release(
                exists.stdout, assets, tag_target
            )
            if missing:
                self._run(
                    "release",
                    "upload",
                    tag,
                    *(str(asset) for asset in missing),
                    "--repo",
                    self.profile.repository,
                )
        self._run(
            "release",
            "edit",
            tag,
            "--repo",
            self.profile.repository,
            "--draft=false",
        )
        previous_runs = self._workflow_run_ids() if wait else set()
        self._run(
            "workflow",
            "run",
            self.profile.workflow,
            "--repo",
            self.profile.repository,
            "--ref",
            tag,
            "-f",
            f"release_tag={tag}",
        )
        if not wait:
            return GitHubPublication(
                bundle.release_id,
                self.profile.repository,
                tag,
                self.profile.workflow,
                "dispatched",
            )
        run_id = self._wait_for_pages(
            tag,
            wait_timeout_seconds,
            previous_runs=previous_runs,
        )
        return GitHubPublication(
            bundle.release_id,
            self.profile.repository,
            tag,
            self.profile.workflow,
            "published",
            run_id,
        )

    def _trusted_target(self) -> str:
        result = self._run(
            "repo",
            "view",
            self.profile.repository,
            "--json",
            "defaultBranchRef",
            "--jq",
            ".defaultBranchRef.name",
        )
        ref = result.stdout.strip()
        if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._/-]*", ref) or ".." in ref:
            raise DeployExecutionError("GitHub returned an unsafe default branch")
        target = self._run(
            "api",
            f"repos/{self.profile.repository}/commits/{ref}",
            "--jq",
            ".sha",
        ).stdout.strip()
        if not re.fullmatch(r"[0-9a-f]{40}", target):
            raise DeployExecutionError("GitHub returned an invalid default-branch commit")
        return target

    def _tag_target(self, tag: str) -> str:
        result = self._run(
            "api", f"repos/{self.profile.repository}/git/ref/tags/{tag}"
        )
        try:
            value = json.loads(result.stdout)
            target_type = str(value["object"]["type"])
            target = str(value["object"]["sha"])
        except (KeyError, TypeError, json.JSONDecodeError) as exc:
            raise DeployExecutionError("GitHub returned invalid release-tag JSON") from exc
        for _ in range(4):
            if target_type == "commit":
                if not re.fullmatch(r"[0-9a-f]{40}", target):
                    break
                return target
            if target_type != "tag" or not re.fullmatch(r"[0-9a-f]{40}", target):
                break
            result = self._run(
                "api", f"repos/{self.profile.repository}/git/tags/{target}"
            )
            try:
                value = json.loads(result.stdout)
                target_type = str(value["object"]["type"])
                target = str(value["object"]["sha"])
            except (KeyError, TypeError, json.JSONDecodeError) as exc:
                raise DeployExecutionError(
                    "GitHub returned invalid annotated-tag JSON"
                ) from exc
        raise DeployExecutionError("release tag does not resolve to a commit")

    @staticmethod
    def _validate_assets(bundle: BundleInfo, assets: tuple[Path, ...]) -> None:
        expected_names = (
            f"{bundle.release_id}.site.tar.zst",
            "release-manifest.json",
            "SHA256SUMS",
        )
        if tuple(asset.name for asset in assets) != expected_names:
            raise DeployExecutionError(
                "release assets must use the canonical bundle, manifest, and checksum names"
            )
        expected_digest = bundle.bundle_sha256.removeprefix("sha256:")
        if not re.fullmatch(r"[0-9a-f]{64}", expected_digest):
            raise DeployExecutionError("bundle has an invalid SHA256")
        digest = _sha256_file(assets[0])
        if digest != expected_digest:
            raise DeployExecutionError("bundle SHA256 does not match bundle metadata")
        if assets[2].read_text(encoding="utf-8") != (
            f"{expected_digest}  {assets[0].name}\n"
        ):
            raise DeployExecutionError("SHA256SUMS does not bind the canonical bundle")
        try:
            manifest = json.loads(assets[1].read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            raise DeployExecutionError("release manifest is not valid JSON") from exc
        if not isinstance(manifest, dict) or manifest.get("release_id") != bundle.release_id:
            raise DeployExecutionError("release manifest does not match the release ID")

    @staticmethod
    def _validate_existing_release(
        payload: str,
        assets: tuple[Path, ...],
        tag_target: str,
    ) -> tuple[Path, ...]:
        try:
            release = json.loads(payload)
        except json.JSONDecodeError as exc:
            raise DeployExecutionError("GitHub CLI returned invalid release JSON") from exc
        if not isinstance(release, dict) or release.get("targetCommitish") != tag_target:
            raise DeployExecutionError(
                "existing release target does not match its immutable tag"
            )
        remote_assets = release.get("assets")
        if not isinstance(remote_assets, list):
            raise DeployExecutionError("existing release has invalid asset metadata")
        expected = {
            asset.name: (asset.stat().st_size, f"sha256:{_sha256_file(asset)}")
            for asset in assets
        }
        actual = {
            str(item.get("name")): (
                int(item.get("size", -1)),
                str(item.get("digest") or ""),
            )
            for item in remote_assets
            if isinstance(item, dict)
        }
        mismatched = {
            name for name in actual.keys() & expected.keys() if actual[name] != expected[name]
        }
        extra = actual.keys() - expected.keys()
        if mismatched or extra:
            raise DeployExecutionError(
                "existing release assets differ; refusing to overwrite immutable assets"
            )
        missing_names = expected.keys() - actual.keys()
        if missing_names and not release.get("isDraft"):
            raise DeployExecutionError(
                "published release is missing immutable assets; refusing to modify it"
            )
        return tuple(asset for asset in assets if asset.name in missing_names)

    def _workflow_run_ids(self) -> set[int]:
        result = self._run(
            "run",
            "list",
            "--repo",
            self.profile.repository,
            "--workflow",
            self.profile.workflow,
            "--limit",
            "20",
            "--json",
            "databaseId",
        )
        try:
            runs = json.loads(result.stdout)
        except json.JSONDecodeError as exc:
            raise DeployExecutionError(
                "GitHub CLI returned invalid workflow JSON"
            ) from exc
        if not isinstance(runs, list):
            raise DeployExecutionError("GitHub CLI workflow JSON must be an array")
        return {
            int(run["databaseId"])
            for run in runs
            if isinstance(run, dict) and run.get("databaseId") is not None
        }

    def _wait_for_pages(
        self,
        tag: str,
        timeout: float,
        *,
        previous_runs: set[int],
    ) -> int:
        deadline = time.monotonic() + timeout
        title = f"Publish {tag}"
        while time.monotonic() < deadline:
            result = self._run(
                "run",
                "list",
                "--repo",
                self.profile.repository,
                "--workflow",
                self.profile.workflow,
                "--limit",
                "20",
                "--json",
                "databaseId,displayTitle,status,conclusion",
            )
            try:
                runs = json.loads(result.stdout)
            except json.JSONDecodeError as exc:
                raise DeployExecutionError(
                    "GitHub CLI returned invalid workflow JSON"
                ) from exc
            for run in runs if isinstance(runs, list) else ():
                if not isinstance(run, dict) or run.get("displayTitle") != title:
                    continue
                run_id = int(run["databaseId"])
                if run_id in previous_runs:
                    continue
                status = run.get("status")
                if status != "completed":
                    break
                if run.get("conclusion") != "success":
                    raise DeployExecutionError(
                        f"Pages workflow failed: {run.get('conclusion')}"
                    )
                return run_id
            time.sleep(3)
        raise DeployExecutionError(f"timed out waiting for Pages workflow for {tag}")

    def _run(self, *args: str, check: bool = True):
        try:
            result = self.runner.run(
                Command(("gh", *args), cwd=Path.cwd(), timeout=300.0)
            )
        except CommandExecutionError as exc:
            raise DeployExecutionError(f"cannot run GitHub CLI: {exc}") from exc
        if check and result.returncode != 0:
            detail = (result.stderr or result.stdout).strip()
            raise DeployExecutionError(
                f"GitHub CLI command failed: {' '.join(args[:2])}"
                + (f": {detail}" if detail else "")
            )
        return result


